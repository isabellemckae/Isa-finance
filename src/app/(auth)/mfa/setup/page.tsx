import { ShieldCheck } from "lucide-react";
import { requireMfaStep } from "@/lib/auth/dal";
import { signOut, startTotpEnrollment } from "@/lib/auth/actions";
import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { ConfirmEnrollmentForm } from "@/components/auth/forms";

export const metadata = { title: "Set up two-factor authentication" };

export default async function SetupPage() {
  await requireMfaStep("mfa-setup");
  const enrollment = await startTotpEnrollment();

  return (
    <Card className="space-y-6">
      <div>
        <ShieldCheck className="mb-3 size-6 text-accent-ink" aria-hidden />
        <h1 className="font-display text-2xl">Protect your finances</h1>
        <p className="mt-1 text-sm text-muted-foreground">
          Two-factor authentication is required. Scan this code with an authenticator app, then enter the 6-digit code
          it shows.
        </p>
      </div>
      {enrollment.error || !enrollment.factorId || !enrollment.qrCode ? (
        <p role="alert" className="rounded-2xl bg-attention-soft px-4 py-3 text-sm text-attention">
          {enrollment.error ?? "Could not start setup."}
        </p>
      ) : (
        <>
          {/* QR code is an SVG data URI generated by Supabase Auth. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={enrollment.qrCode}
            alt="QR code for your authenticator app"
            className="mx-auto size-48 rounded-2xl bg-white p-3"
          />
          <details className="text-sm">
            <summary className="cursor-pointer text-muted-foreground">Can&apos;t scan? Enter the key manually</summary>
            <code className="mt-2 block break-all rounded-xl bg-surface-muted p-3 font-mono text-xs">
              {enrollment.secret}
            </code>
          </details>
          <ConfirmEnrollmentForm factorId={enrollment.factorId} />
        </>
      )}
      <form action={signOut}>
        <Button type="submit" variant="link" className="w-full">
          Sign out
        </Button>
      </form>
    </Card>
  );
}
